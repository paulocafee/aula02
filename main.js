// string = textos
// boolean = verdadeiro / falso
// float = numeros 'quebrados' com virgulas
// int = numeros inteiros

// variaveis
var idadeUsuario = 16
// exibe mensagem na tela
// o simbolo "+" quando usado com texto a função dele é "concatenar" 
console.log("idade do usuario: " + idadeUsuario)
// = é o operador de atribuição
// == é o operador de comparação iguais
// > operador maior
// < operador menor
// >= operador maior ou igual
// <= operador menor ou igual
console.log(idadeUsuario >= 18)
// ao ter a comparação eu tenho o resultado em boolean

// if -> se (pergunta) e executa se for verdade
// senão -> else executa caso o if for falso
if (idadeUsuario >= 18) {
  console.log("O usuario pode dirigir!")
} else {
  console.log("Desculpa você ainda não pode dirigir!")
}








